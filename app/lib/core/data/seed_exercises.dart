const _illustrated = {'bird_dog'};

ExerciseMedia _img(String id, String name) {
  final ext = _illustrated.contains(id) ? 'png' : 'jpg';
  return ExerciseMedia(
    kind: MediaKind.imagePair,
    src: 'assets/exercises/frames/${id}_start.$ext',
    endSrc: 'assets/exercises/frames/${id}_end.$ext',
    alt: name,
  );
}

